#!/usr/bin/env Rscript
# =============================================================================
# plot_wealth_accounts_bar_tikz.R
#
# Companion to plot_wealth_accounts_bar.R: reads the same CSV, computes the
# averaged EOA/CA wealth-bucket composition, and emits a standalone
# .tex file containing a tikzpicture (vector, document-native fonts).
#
# Usage:
#   Rscript plot_wealth_accounts_bar_tikz.R \
#     --csv ../data/value_buckets_minimal.csv \
#     --out_tex ../graphics/wealth_accounts_bar.tex
# =============================================================================

suppressPackageStartupMessages({
  library(optparse)
  library(readr)
  library(dplyr)
  library(stringr)
})

option_list <- list(
  make_option(c("-i", "--csv"), type = "character",
              help = "Input CSV path (required)"),
  make_option(c("-o", "--out_tex"), type = "character",
              default = "../graphics/wealth_accounts_bar.tex",
              help = "Output .tex path [default: %default]"),
  make_option(c("--scale"), type = "double", default = 0.130,
              help = "cm per percentage point (natural bar width = 100*scale) [default: %default]")
)
opt <- parse_args(OptionParser(option_list = option_list))
if (is.null(opt$csv) || !file.exists(opt$csv)) stop("Error: Input CSV not found.")

# ---- Load + normalise (matches plot_wealth_accounts_bar.R logic) ----
df <- read_csv(opt$csv, show_col_types = FALSE) %>%
  mutate(
    block       = as.integer(block),
    wallet_type = str_trim(as.character(wallet_type)),
    bucket      = str_trim(as.character(bucket)),
    wallet_pct  = suppressWarnings(as.numeric(wallet_pct))
  ) %>%
  filter(!is.na(block), !is.na(wallet_pct),
         wallet_type %in% c("EOA", "CA"))

if (max(df$wallet_pct, na.rm = TRUE) <= 1.05) df$wallet_pct <- df$wallet_pct * 100

df <- df %>%
  mutate(
    bucket_norm = bucket %>%
      str_replace_all("[\\s\\$]", "") %>%
      str_replace_all("[\u2013\u2014]", "-"),
    bucket_label = case_when(
      bucket_norm %in% c("0-1", "0-1USD")                     ~ "0-1",
      bucket_norm %in% c("1-100", "1-100USD")                  ~ "1-100",
      bucket_norm %in% c("100-1K", "100-1000", "100-1000USD") ~ "100-1K",
      bucket_norm %in% c("1K-10K", "1000-10000", "1K-10000")  ~ "1K-10K",
      bucket_norm %in% c("10K-100K", "10000-100000")           ~ "10K-100K",
      bucket_norm %in% c(">100K", "100K+", "100000+")          ~ ">100K",
      TRUE ~ bucket
    )
  )

level_order <- c("0-1", "1-100", "100-1K", "1K-10K", "10K-100K", ">100K")

df_avg <- df %>%
  group_by(wallet_type, bucket_label) %>%
  summarise(mean_pct = mean(wallet_pct, na.rm = TRUE), .groups = "drop")

get_vec <- function(wtype) {
  sapply(level_order, function(b) {
    v <- df_avg$mean_pct[df_avg$wallet_type == wtype & df_avg$bucket_label == b]
    if (length(v) == 0) 0 else v
  })
}
eoa_v <- get_vec("EOA")
ca_v  <- get_vec("CA")

# ---- Emit TikZ ----
emit_tikz <- function(file, eoa_v, ca_v, scl) {
  fmt <- function(x) formatC(x, format = "f", digits = 1)
  eoa_s <- c(0, head(cumsum(eoa_v), -1)); eoa_m <- eoa_s + eoa_v / 2
  ca_s  <- c(0, head(cumsum(ca_v),  -1)); ca_m  <- ca_s  + ca_v  / 2

  letters_c <- c("A", "B", "C", "D", "E", "F")
  hex       <- c("264653", "2A9D8F", "8AB17D", "E9C46A", "F4A261", "E76F51")
  bin_lbl   <- c("0--1", "1--100", "100--1K", "1K--10K", "10K--100K", "$>$100K")

  L <- c()
  L <- c(L, "% Auto-generated by plot_wealth_accounts_bar_tikz.R - do not edit by hand.")
  L <- c(L, "% Requires: \\usepackage{tikz}")
  L <- c(L, "\\resizebox{\\linewidth}{!}{%")
  L <- c(L, "\\begin{tikzpicture}[")
  L <- c(L, "    seglabel/.style={text=white, font=\\sffamily\\small\\bfseries},")
  L <- c(L, "    smalllabel/.style={font=\\sffamily\\scriptsize\\bfseries, anchor=south},")
  L <- c(L, "    leader/.style={draw=gray!55, line width=0.3pt},")
  L <- c(L, "    axislabel/.style={font=\\sffamily\\footnotesize, text=gray!40!black},")
  L <- c(L, "    walletlabel/.style={font=\\sffamily\\small\\bfseries, anchor=east, text=gray!30!black},")
  L <- c(L, "    gridline/.style={draw=gray!30, dashed, line width=0.3pt},")
  L <- c(L, "    legendlabel/.style={font=\\sffamily\\footnotesize, anchor=west, text=gray!20!black},")
  L <- c(L, "    legendtitle/.style={font=\\sffamily\\footnotesize\\bfseries, anchor=south, text=gray!10!black},")
  L <- c(L, "  ]")
  for (i in seq_along(letters_c)) {
    L <- c(L, sprintf("  \\definecolor{wb%s}{HTML}{%s}", letters_c[i], hex[i]))
  }
  L <- c(L, "")
  L <- c(L, sprintf("  \\pgfmathsetmacro{\\scl}{%.4f}  %% cm per percentage point", scl))
  L <- c(L, "  \\pgfmathsetmacro{\\bh}{0.7}            % bar height (cm)")
  L <- c(L, "  \\pgfmathsetmacro{\\yCA}{0}")
  L <- c(L, "  \\pgfmathsetmacro{\\yEOA}{1.5}          % gap between bars allows staggered labels")
  L <- c(L, "")
  L <- c(L, "  % Gridlines")
  L <- c(L, "  \\foreach \\p in {0,20,40,60,80,100} {")
  L <- c(L, "    \\draw[gridline] ({\\p*\\scl}, -0.05) -- ({\\p*\\scl}, {\\yEOA+\\bh+0.05});")
  L <- c(L, "  }")
  L <- c(L, "")
  L <- c(L, "  % Wallet-type labels (y-axis)")
  L <- c(L, "  \\node[walletlabel] at (-0.15, {\\yCA+\\bh/2})  {CA};")
  L <- c(L, "  \\node[walletlabel] at (-0.15, {\\yEOA+\\bh/2}) {EOA};")
  L <- c(L, "")

  emit_bar <- function(v, s, m, yvar, tag) {
    out <- c(sprintf("  %% --- %s bar ---", tag))
    for (i in seq_along(v)) {
      if (v[i] <= 0) next
      out <- c(out, sprintf(
        "  \\fill[wb%s] ({%.4f*\\scl}, %s) rectangle ({%.4f*\\scl}, {%s+\\bh});",
        letters_c[i], s[i], yvar, s[i] + v[i], yvar
      ))
    }
    for (i in seq_along(v)) {
      if (v[i] >= 6) {
        out <- c(out, sprintf(
          "  \\node[seglabel] at ({%.4f*\\scl}, {%s+\\bh/2}) {%s\\%%};",
          m[i], yvar, fmt(v[i])
        ))
      }
    }
    # Outside labels for small segments (< 6%): progressive left-nudge by rank
    # from rightmost + alternating heights so labels never collide.
    # Text colour is darkened (wbX!55..65!black) so light yellows stay legible on white.
    small_idx <- which(v < 6 & v > 0)
    if (length(small_idx) > 0) {
      step_pp <- 5.0  # horizontal spacing between adjacent small labels (pp)
      ranked  <- small_idx[order(-m[small_idx])]
      darkmix <- c(A=65, B=65, C=65, D=55, E=65, F=65)  # wbD (yellow) needs more black
      for (rank in seq_along(ranked)) {
        i      <- ranked[rank]
        nudge  <- (rank - 1) * step_pp
        x_lab  <- m[i] - nudge
        y_off  <- if (rank %% 2 == 0) 0.48 else 0.22   # alternate heights
        mix    <- darkmix[[letters_c[i]]]
        out <- c(out, sprintf(
          "  \\draw[leader] ({%.4f*\\scl}, {%s+\\bh}) -- ({%.4f*\\scl}, {%s+\\bh+%.2f});",
          m[i], yvar, x_lab, yvar, y_off
        ))
        out <- c(out, sprintf(
          "  \\node[smalllabel, text=wb%s!%d!black] at ({%.4f*\\scl}, {%s+\\bh+%.2f}) {%s\\%%};",
          letters_c[i], mix, x_lab, yvar, y_off, fmt(v[i])
        ))
      }
    }
    out
  }

  L <- c(L, emit_bar(eoa_v, eoa_s, eoa_m, "\\yEOA", "EOA"), "")
  L <- c(L, emit_bar(ca_v,  ca_s,  ca_m,  "\\yCA",  "CA"),  "")

  L <- c(L, "  % X-axis tick labels and title")
  L <- c(L, "  \\foreach \\p in {0,20,40,60,80,100} {")
  L <- c(L, "    \\node[axislabel, anchor=north] at ({\\p*\\scl}, {\\yCA-0.1}) {\\p\\%};")
  L <- c(L, "  }")
  L <- c(L, "  \\node[axislabel] at ({50*\\scl}, {\\yCA-0.95}) {Average share (\\%)};")
  L <- c(L, "")
  L <- c(L, "  % Legend (two rows: title above, six swatches below)")
  L <- c(L, "  \\pgfmathsetmacro{\\legy}{-2.20}")
  L <- c(L, sprintf("  \\node[legendtitle] at ({50*\\scl}, {\\legy+0.30}) {Wealth bins [USD]};"))
  bar_w <- 100 * scl
  step  <- bar_w / 6
  for (i in seq_along(bin_lbl)) {
    cx  <- (i - 0.5) * step      # centre of i-th slot, in cm
    sw0 <- cx - 0.55              # swatch left edge
    sw1 <- sw0 + 0.25             # swatch right edge (0.25cm wide)
    tx  <- sw1 + 0.07             # label x position (just right of swatch)
    L <- c(L, sprintf(
      "  \\fill[wb%s] (%.4f, {\\legy-0.12}) rectangle (%.4f, {\\legy+0.12});",
      letters_c[i], sw0, sw1
    ))
    L <- c(L, sprintf(
      "  \\node[legendlabel] at (%.4f, \\legy) {%s};",
      tx, bin_lbl[i]
    ))
  }
  L <- c(L, "\\end{tikzpicture}%")
  L <- c(L, "}")

  writeLines(L, file)
}

dir.create(dirname(opt$out_tex), showWarnings = FALSE, recursive = TRUE)
emit_tikz(opt$out_tex, eoa_v, ca_v, opt$scale)
cat(sprintf("[ok] Saved TikZ: %s\n", opt$out_tex))
cat(sprintf("[info] EOA shares: %s\n",
            paste(sprintf("%s=%.2f%%", level_order, eoa_v), collapse = ", ")))
cat(sprintf("[info] CA shares:  %s\n",
            paste(sprintf("%s=%.2f%%", level_order, ca_v), collapse = ", ")))